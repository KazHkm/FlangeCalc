def get_brands():
    return list(HTW_DATA.keys())


def get_models(brand):
    return list(HTW_DATA.get(brand, {}).keys())


def get_hex_sizes(brand, model):
    return list(HTW_DATA.get(brand, {}).get(model, {}).keys())


def get_table(brand, model, hex_size):
    return HTW_DATA[brand][model][hex_size]


def bar_to_psi(bar):
    return bar * 14.5038


def psi_to_bar(psi):
    return psi / 14.5038


def nm_to_lbft(nm):
    return nm * 0.737562


def lbft_to_nm(lbft):
    return lbft / 0.737562